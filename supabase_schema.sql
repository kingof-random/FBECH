-- F-BECH Supabase schema. Run in Supabase SQL Editor if you prefer manual setup.
CREATE TABLE IF NOT EXISTS rules (
 id TEXT PRIMARY KEY, part TEXT NOT NULL, article TEXT NOT NULL, number TEXT NOT NULL,
 title TEXT NOT NULL, kind TEXT, priority TEXT, page INTEGER, article_title TEXT, part_title TEXT,
 body TEXT, plain TEXT, engineering TEXT, notes TEXT, components TEXT, xrefs TEXT, figures TEXT,
 table_data TEXT, status TEXT, sort_order INTEGER
);
CREATE TABLE IF NOT EXISTS checks (
 id TEXT PRIMARY KEY, rule_id TEXT, title TEXT, component TEXT, criterion TEXT, method TEXT,
 evidence_required TEXT, eval TEXT, min_val DOUBLE PRECISION, max_val DOUBLE PRECISION, unit TEXT,
 label TEXT, priority TEXT, status TEXT, measured TEXT, remarks TEXT, assignee TEXT,
 updated_at TEXT, sort_order INTEGER
);
CREATE TABLE IF NOT EXISTS evidence (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, check_id TEXT, filename TEXT,
 stored TEXT, note TEXT, uploaded_at TEXT
);
CREATE TABLE IF NOT EXISTS docs (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, category TEXT, title TEXT, body TEXT,
 ref TEXT, created_at TEXT, updated_at TEXT
);
CREATE TABLE IF NOT EXISTS issues (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, title TEXT, detail TEXT, severity TEXT,
 status TEXT, rule_id TEXT, owner TEXT, created_at TEXT, updated_at TEXT
);
CREATE TABLE IF NOT EXISTS revisions (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, rev TEXT, date TEXT, author TEXT, description TEXT
);
CREATE TABLE IF NOT EXISTS meta (key TEXT PRIMARY KEY, value TEXT);
CREATE TABLE IF NOT EXISTS users (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, username TEXT UNIQUE NOT NULL,
 password_hash TEXT NOT NULL, created_at TEXT NOT NULL
);
